#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md: the open-source packages whose code ships in
// the built app (dist/), its service worker, and the interactive HTML export,
// with each one's licence and copyright line and the full licence text, read
// from node_modules. Run `npm run notices` after adding or removing a runtime
// dependency.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))

/** Bundled from build tooling rather than listed in "dependencies". */
const TOOLING_RUNTIME = [
  'workbox-window', // service worker registration (virtual:pwa-register)
  'workbox-core', // the generated service worker
  'workbox-precaching',
  'workbox-routing',
  'workbox-strategies',
]
/**
 * Listed on purpose though they are devDependencies, without their own
 * dependencies: src/schema/validators.generated.js is code generated by Ajv
 * and includes its ucs2length helper (scripts/build-validators.mjs).
 */
const DERIVED_FROM = ['ajv']
/** What src/viewer (inlined into every interactive HTML export) imports. */
const VIEWER_ROOTS = ['react', 'react-dom', '@xyflow/react']

/**
 * The installed copy of `name` that code in `fromDir` gets, found as Node does:
 * in node_modules/ of `fromDir` and then of each folder above it, up to ROOT.
 * So a nested copy (e.g. @xyflow/react/node_modules/zustand) is found first.
 */
function resolvePackage(name, fromDir) {
  let dir = fromDir
  for (;;) {
    if (path.basename(dir) !== 'node_modules') {
      const pkgDir = path.join(dir, 'node_modules', name)
      const file = path.join(pkgDir, 'package.json')
      if (existsSync(file))
        return { name, dir: pkgDir, json: JSON.parse(readFileSync(file, 'utf8')) }
    }
    if (dir === ROOT || path.dirname(dir) === dir) break
    dir = path.dirname(dir)
  }
  throw new Error(`${name} is not installed; run npm ci first`)
}

/**
 * Every installed package reachable from `roots` through "dependencies", each
 * dependency resolved from the folder of the package that needs it. Type
 * packages are left out. Returns a map from package folder to package.
 */
function closure(roots) {
  const seen = new Map()
  const queue = roots.map((name) => ({ name, from: ROOT }))
  while (queue.length > 0) {
    const { name, from } = queue.shift()
    if (name.startsWith('@types/')) continue
    const pkg = resolvePackage(name, from)
    if (seen.has(pkg.dir)) continue
    seen.set(pkg.dir, pkg)
    for (const dep of Object.keys(pkg.json.dependencies ?? {})) {
      queue.push({ name: dep, from: pkg.dir })
    }
  }
  return seen
}

function licenceText(dir) {
  const file = readdirSync(dir).find((name) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(name))
  return file ? readFileSync(path.join(dir, file), 'utf8').replace(/\r\n?/g, '\n').trim() : null
}

function copyrightLine(text) {
  const line = text
    ?.split('\n')
    .map((l) => l.trim())
    .find((l) => /^(\(c\)|©|copyright\b)/i.test(l) && !/copyright (notice|holders?)\b/i.test(l))
  return line ?? '(no copyright line in the licence file)'
}

const app = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8'))
const shipped = closure([...Object.keys(app.dependencies ?? {}), ...TOOLING_RUNTIME])
for (const name of DERIVED_FROM) {
  const pkg = resolvePackage(name, ROOT)
  shipped.set(pkg.dir, pkg)
}
const inViewer = closure(VIEWER_ROOTS)
const packages = [...shipped.values()]
// Two installed versions of one package are told apart by their version.
const versions = new Map()
for (const { name, json } of packages) {
  versions.set(name, new Set([...(versions.get(name) ?? []), json.version]))
}
const label = ({ name, json }) => (versions.get(name).size > 1 ? `${name}@${json.version}` : name)
const entries = [...new Map(packages.map((pkg) => [label(pkg), pkg])).entries()].sort(([a], [b]) =>
  a.localeCompare(b),
)
const viewerLabels = new Set([...inViewer.values()].map(label))

const rows = []
const texts = []
for (const [name, { dir, json }] of entries) {
  const text = licenceText(dir)
  const licence = typeof json.license === 'string' ? json.license : 'see licence text'
  const where = viewerLabels.has(name) ? 'app, HTML export' : 'app'
  rows.push(`| ${name} | ${licence} | ${copyrightLine(text).replace(/\|/g, '\\|')} | ${where} |`)
  texts.push(`### ${name}\n\n\`\`\`text\n${text ?? `Licensed under ${licence}.`}\n\`\`\``)
}

const out = `# Third-party notices

Mind Map Studio is MIT licensed (see [LICENSE](LICENSE)). The built app, its service worker and
the interactive HTML export include code from the open-source packages below. "HTML export"
marks the packages inlined into every exported \`.html\` file. Ajv is listed because the app's
precompiled schema validators are code generated by it.

Generated by \`npm run notices\` (scripts/third-party-notices.mjs) from the installed packages.

| Package | Licence | Copyright | Shipped in |
|---|---|---|---|
${rows.join('\n')}

## Licence texts

${texts.join('\n\n')}
`
writeFileSync(path.join(ROOT, 'THIRD_PARTY_NOTICES.md'), out)
console.log(`THIRD_PARTY_NOTICES.md: ${entries.length} packages`)
