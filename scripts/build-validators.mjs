#!/usr/bin/env node
/**
 * Precompiles the JSON schemas into plain validation functions (#181), so the
 * app never compiles code at run time and its Content-Security-Policy needs no
 * 'unsafe-eval'. Same options as scripts/validate.mjs. Run after changing a
 * schema: `npm run validators`; a test fails while the committed file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { AJV_OPTIONS, KIND_TO_SCHEMA, ROOT, schemaFiles } from './validate.mjs'

export const OUTPUT = path.join(ROOT, 'src', 'schema', 'validators.generated.js')

/** The export name of each document kind: "analysis-request" → analysis_request. */
export const exportName = (kind) => kind.replace(/-/g, '_')

// Ajv's own helper, inlined so the generated file imports nothing.
const UCS2LENGTH = `function ucs2length(str) {
  const len = str.length
  let length = 0
  let pos = 0
  let value
  while (pos < len) {
    length++
    value = str.charCodeAt(pos++)
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      value = str.charCodeAt(pos)
      if ((value & 0xfc00) === 0xdc00) pos++
    }
  }
  return length
}`

export function generateValidatorsSource(root = ROOT) {
  const ajv = new Ajv2020({ ...AJV_OPTIONS, code: { source: true, esm: true } })
  for (const file of schemaFiles(root)) {
    ajv.addSchema(JSON.parse(readFileSync(path.join(root, 'schemas', file), 'utf8')))
  }
  const refs = Object.fromEntries(
    Object.entries(KIND_TO_SCHEMA).map(([kind, schema]) => [exportName(kind), schema]),
  )
  const code = standaloneCode(ajv, refs)
    .replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, 'ucs2length')
    // ES modules are strict already; mid-file the directive would only be a string.
    .replace(/^"use strict";/, '')
  if (/require\(/.test(code)) throw new Error('generated validators still require a module')
  return `// Generated by scripts/build-validators.mjs from schemas/*.schema.json. Do not edit.\n${UCS2LENGTH}\n${code}\n`
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generateValidatorsSource())
  console.log(`wrote ${path.relative(ROOT, OUTPUT)}`)
}
